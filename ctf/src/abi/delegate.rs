        fn abi_encode_raw(&self, out: &mut alloy_sol_types::private::Vec<u8>) {
            match self {
                Self::owner(inner) => {
                    <ownerCall as alloy_sol_types::SolCall>::abi_encode_raw(inner, out)
                }
                Self::pwn(inner) => {
                    <pwnCall as alloy_sol_types::SolCall>::abi_encode_raw(inner, out)
                }
            }
        }
