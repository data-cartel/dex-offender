        fn abi_encode_raw(&self, out: &mut alloy_sol_types::private::Vec<u8>) {
            match self {
                Self::locked(inner) => {
                    <lockedCall as alloy_sol_types::SolCall>::abi_encode_raw(inner, out)
                }
                Self::unlock(inner) => {
                    <unlockCall as alloy_sol_types::SolCall>::abi_encode_raw(inner, out)
                }
            }
        }
